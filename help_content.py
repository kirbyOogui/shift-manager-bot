def search(query: str) -> list:
    """クエリに一致するヘルプアイテムをスコア順で返す（最大10件）。"""
    # 「仕事名」→「プロファイル」も検索対象に含める
    expanded = query.replace("仕事名", "プロファイル")
    scored = []
    for item in HELP_ITEMS:
        if item.get("detail") == "__LIVE_SETTINGS__":
            keywords_match = any(kw in query or kw in expanded for kw in item["keywords"])
            if keywords_match or item["title"] in query or query in item["title"]:
                scored.append((5, item))
            continue
        score = 0
        for kw in item["keywords"]:
            if kw in query or kw in expanded:
                score += 2
        if item["title"] in query or query in item["title"]:
            score += 3
        if item["category"] in query or item["category"] in expanded:
            score += 2
        if score > 0:
            scored.append((score, item))
    scored.sort(key=lambda x: -x[0])
    return [item for _, item in scored[:10]]


def get_by_id(item_id: str) -> dict | None:
    """IDでヘルプアイテムを取得する。"""
    for item in HELP_ITEMS:
        if item["id"] == item_id:
            return item
    return None


def get_category_list() -> list[dict]:
    """カテゴリ一覧をボタン用データで返す。"""
    result = []
    for cat in _CATEGORY_ORDER:
        icon = _CATEGORY_ICON.get(cat, "")
        display = _CATEGORY_DISPLAY.get(cat, cat)
        result.append({"label": f"{icon} {display}", "cat": cat})
    return result


def get_category_items(cat: str) -> list[dict]:
    """指定カテゴリの全アイテムを返す。"""
    return [item for item in HELP_ITEMS if item["category"] == cat]


def get_category_text(cat: str) -> str:
    """指定カテゴリのアイテム一覧（タイトル＋概要）を返す。"""
    items = get_category_items(cat)
    icon = _CATEGORY_ICON.get(cat, "")
    display = _CATEGORY_DISPLAY.get(cat, cat)
    lines = [f"{icon} {display}", ""]
    for item in items:
        lines.append(f"▶ {item['title']}")
        lines.append(f"  {item.get('summary', '')}")
    lines += ["", "下のボタンをタップすると詳細を確認できます。"]
    return "\n".join(lines)


def get_all_text() -> str:
    """カテゴリ一覧の案内テキストを返す（全機能ダンプは廃止）。"""
    cats = get_category_list()
    lines = ["📖 機能カテゴリ一覧", ""]
    for c in cats:
        items = get_category_items(c["cat"])
        lines.append(f"{c['label']}（{len(items)}機能）")
    lines += ["", "下のボタンからカテゴリを選んでください。"]
    return "\n".join(lines)
